  }

  Widget _buildSavedDeviceCard(DeviceProfileModel device, DeviceConnectionService service) {
    final isBluetooth = device.protocol == 'bluetooth';
    final isOnline = isBluetooth
        ? (service.isConnected && service.connectionMode == ConnectionMode.bluetooth && service.selectedDevice?.address == device.macAddress)
        : (service.isConnected && service.connectionMode == ConnectionMode.wifi && service.connectedIp == device.host);

    final iconColor = isBluetooth ? const Color(0xFF2A5EE8) : const Color(0xFFF79E66);
    final iconBgColor = iconColor.withValues(alpha: 0.1);

    return GestureDetector(
      onTap: () async {
        if (isOnline) return; // Already connected
        
        // Putuskan koneksi yang ada jika sedang nyambung ke device lain
        if (service.isConnected || service.isConnecting) {
          service.disconnect();
          await Future.delayed(const Duration(milliseconds: 200)); // Beri waktu cleanup
        }

        if (isBluetooth && device.macAddress != null) {
          service.setConnectionMode(ConnectionMode.bluetooth);
          setState(() => _connectingDeviceId = device.id);
          await service.connectBluetoothByMac(device.macAddress!);
          if (mounted) {
            setState(() => _connectingDeviceId = null);
            if (!service.isConnected) {
              ScaffoldMessenger.of(context).showSnackBar(
                SnackBar(content: Text(service.statusMessage), backgroundColor: Colors.red),
              );
            }
          }
        } else if (!isBluetooth && device.host != null) {
          service.setConnectionMode(ConnectionMode.wifi);
          setState(() => _connectingDeviceId = device.id);
          await service.connectWifi(device.host!, device.port?.toString() ?? '');
          if (mounted) {
            setState(() => _connectingDeviceId = null);
            if (!service.isConnected) {
              ScaffoldMessenger.of(context).showSnackBar(
                SnackBar(content: Text(service.statusMessage), backgroundColor: Colors.red),
              );
            }
          }
        }
      },
      child: Container(
        margin: const EdgeInsets.only(bottom: 12),
        padding: const EdgeInsets.all(16),
        decoration: BoxDecoration(
          color: Colors.white,
          borderRadius: BorderRadius.circular(16),
          border: Border.all(color: Colors.grey.shade200),
        ),
        child: Row(
          children: [
            Container(
              width: 50,
              height: 50,
              decoration: BoxDecoration(
                color: iconBgColor,
                borderRadius: BorderRadius.circular(12),
              ),
              child: Icon(
                isBluetooth ? Icons.bluetooth : Icons.wifi,
                color: iconColor,
              ),
            ),
            const SizedBox(width: 16),
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    device.label,
                    style: const TextStyle(
                      fontWeight: FontWeight.bold,
                      fontSize: 16,
                      color: Color(0xFF0A122C),
                    ),
                  ),
                  const SizedBox(height: 4),
                  Text(
                    '${device.hardwareVariant ?? 'Hardware Kit'} • ${device.macAddress ?? device.host ?? ''}',
                    style: TextStyle(
                      fontSize: 12,
                      color: Colors.grey.shade500,
                    ),
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                  ),
                ],
              ),
            ),
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
              decoration: BoxDecoration(
                color: isOnline ? const Color(0xFFE8F5E9) : (_connectingDeviceId == device.id ? Colors.blue.shade50 : Colors.grey.shade100),
                borderRadius: BorderRadius.circular(20),
                border: Border.all(color: isOnline ? Colors.green.shade200 : (_connectingDeviceId == device.id ? Colors.blue.shade200 : Colors.grey.shade300)),
              ),
              child: Row(
                children: [
                  if (_connectingDeviceId == device.id)
                    const SizedBox(
                      width: 10,
                      height: 10,
                      child: CircularProgressIndicator(strokeWidth: 2),
                    )
                  else
                    Container(
                      width: 6,
                      height: 6,
                      decoration: BoxDecoration(
                        shape: BoxShape.circle,
                        color: isOnline ? Colors.green : Colors.grey,
                      ),
                    ),
                  const SizedBox(width: 6),
                  Text(
                    _connectingDeviceId == device.id ? 'Connecting...' : (isOnline ? 'Online' : 'Offline'),
                    style: TextStyle(
                      fontSize: 12,
                      fontWeight: FontWeight.bold,
                      color: _connectingDeviceId == device.id ? Colors.blue.shade700 : (isOnline ? Colors.green.shade700 : Colors.grey.shade600),
                    ),
                  ),
                ],
              ),
            ),
            if (isOnline) ...[
              const SizedBox(width: 12),
              InkWell(
                onTap: () => service.disconnect(),
                borderRadius: BorderRadius.circular(20),
                child: Container(
                  padding: const EdgeInsets.all(6),
                  decoration: BoxDecoration(
                    color: Colors.red.shade50,
                    shape: BoxShape.circle,
                  ),
                  child: Icon(
                    Icons.power_settings_new_rounded,
                    color: Colors.red.shade400,
                    size: 20,
                  ),
                ),
              ),
            ],
            const SizedBox(width: 8),
            InkWell(
              onTap: () => _showDeviceDetailsModal(device),
              borderRadius: BorderRadius.circular(20),
              child: Padding(
                padding: const EdgeInsets.all(4.0),
                child: Icon(Icons.more_vert, color: Colors.grey.shade400, size: 20),
              ),
            ),
          ],
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return ListenableBuilder(
      listenable: DeviceConnectionService.instance,
      builder: (context, _) {
        final service = DeviceConnectionService.instance;
        final isBluetoothMode = service.connectionMode == ConnectionMode.bluetooth;
        
        final primaryColor = isBluetoothMode ? const Color(0xFF2A5EE8) : const Color(0xFFF79E66);
        final unselectedIconColor = Colors.grey.shade400;

        // Sort devices: Online first
        List<DeviceProfileModel> sortedDevices = List.from(_savedDevices);
        sortedDevices.sort((a, b) {
          final isAOnline = (a.protocol == 'bluetooth' && service.isConnected && service.connectionMode == ConnectionMode.bluetooth && service.selectedDevice?.address == a.macAddress) ||
                            (a.protocol == 'websocket' && service.isConnected && service.connectionMode == ConnectionMode.wifi && service.connectedIp == a.host);
          final isBOnline = (b.protocol == 'bluetooth' && service.isConnected && service.connectionMode == ConnectionMode.bluetooth && service.selectedDevice?.address == b.macAddress) ||
                            (b.protocol == 'websocket' && service.isConnected && service.connectionMode == ConnectionMode.wifi && service.connectedIp == b.host);
          if (isAOnline && !isBOnline) return -1;
          if (!isAOnline && isBOnline) return 1;
          return 0;
        });

        // Filter based on search
        final query = _searchController.text.toLowerCase();
        if (query.isNotEmpty) {
          sortedDevices = sortedDevices.where((d) => 
            d.label.toLowerCase().contains(query) || 
            (d.macAddress != null && d.macAddress!.toLowerCase().contains(query)) ||
            (d.host != null && d.host!.toLowerCase().contains(query))
          ).toList();
        }

        return Scaffold(
          backgroundColor: const Color(0xFFF4F7FB),
          body: SafeArea(
            child: Padding(
              padding: const EdgeInsets.fromLTRB(24, 24, 24, 0),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    children: [
                      if (widget.showBackButton)
                        Padding(
                          padding: const EdgeInsets.only(right: 16.0),
                          child: InkWell(
                            onTap: () => Navigator.pop(context),
                            child: const Icon(Icons.arrow_back_ios, color: Color(0xFF003092), size: 20),
                          ),
                        ),
                      const Text(
                        'My Devices',
                        style: TextStyle(
                          fontSize: 24,
                          fontWeight: FontWeight.w900,
                          color: Color(0xFF003092),
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 24),

                  // Connect New Device Card
                  Container(
                    padding: const EdgeInsets.all(16),
                    decoration: BoxDecoration(
                      color: Colors.white,
                      borderRadius: BorderRadius.circular(24),
                      boxShadow: [
                        BoxShadow(
                          color: Colors.black.withValues(alpha: 0.03),
                          blurRadius: 10,
                          offset: const Offset(0, 4),
                        ),
                      ],
                    ),
                    child: Row(
                      children: [
                        // Vertical Toggle
                        Container(
                          padding: const EdgeInsets.symmetric(vertical: 8, horizontal: 8),
                          decoration: BoxDecoration(
                            color: const Color(0xFFF4F7FB),
                            borderRadius: BorderRadius.circular(30),
                          ),
                          child: Column(
                            children: [
                              GestureDetector(
                                onTap: () => service.setConnectionMode(ConnectionMode.bluetooth),
                                child: Container(
                                  width: 40,
                                  height: 40,
                                  decoration: BoxDecoration(
                                    color: isBluetoothMode ? primaryColor : Colors.transparent,
                                    shape: BoxShape.circle,
                                  ),
                                  child: Icon(
                                    Icons.bluetooth,
                                    color: isBluetoothMode ? Colors.white : unselectedIconColor,
                                    size: 20,
                                  ),
                                ),
                              ),
                              const SizedBox(height: 8),
                              GestureDetector(
                                onTap: () => service.setConnectionMode(ConnectionMode.wifi),
                                child: Container(
                                  width: 40,
                                  height: 40,
                                  decoration: BoxDecoration(
                                    color: !isBluetoothMode ? primaryColor : Colors.transparent,
                                    shape: BoxShape.circle,
                                  ),
                                  child: Icon(
                                    Icons.wifi,
                                    color: !isBluetoothMode ? Colors.white : unselectedIconColor,
                                    size: 20,
                                  ),
                                ),
                              ),
                            ],
                          ),
                        ),
                        const SizedBox(width: 16),
                        // Content
                        Expanded(
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              const Text(
                                'Connect New Device',
                                style: TextStyle(
                                  fontSize: 16,
                                  fontWeight: FontWeight.w800,
                                  color: Color(0xFF0A122C),
                                ),
                              ),
                              const SizedBox(height: 4),
                              Text(
                                'Ready to pair a new hardware kit to your workspace.',
                                style: TextStyle(
                                  fontSize: 12,
                                  color: Colors.grey.shade600,
                                  height: 1.4,
                                ),
                              ),
                              const SizedBox(height: 12),
                              SizedBox(
                                width: double.infinity,
                                height: 40,
                                child: ElevatedButton(
                                  onPressed: (service.isConnecting && _connectingDeviceId == null) ? null : (isBluetoothMode 
