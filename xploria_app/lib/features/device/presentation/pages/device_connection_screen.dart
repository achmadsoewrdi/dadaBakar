                    decoration: InputDecoration(
                      hintText: 'Nama Perangkat',
                      border: OutlineInputBorder(borderRadius: BorderRadius.circular(12)),
                    ),
                  ),
                  
                  const SizedBox(height: 24),
                  
                  Row(
                    children: [
                      Expanded(
                        child: OutlinedButton(
                          onPressed: isDeleting || isSaving ? null : () async {
                            final confirm = await showDialog<bool>(
                              context: context,
                              builder: (ctx) => AlertDialog(
                                title: const Text('Hapus Perangkat?'),
                                content: const Text('Perangkat ini akan dihapus dari daftar tersimpan.'),
                                actions: [
                                  TextButton(onPressed: () => Navigator.pop(ctx, false), child: const Text('Batal')),
                                  TextButton(
                                    onPressed: () => Navigator.pop(ctx, true), 
                                    child: const Text('Hapus', style: TextStyle(color: Colors.red))
                                  ),
                                ],
                              )
                            );
                            
                            if (confirm == true) {
                              setModalState(() => isDeleting = true);
                              try {
                                await DeviceApiService().deleteDevice(device.id);
                                if (mounted) {
                                  Navigator.pop(context);
                                  _loadSavedDevices();
                                }
                              } catch (e) {
                                if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(e.toString())));
                              }
                              setModalState(() => isDeleting = false);
                            }
                          },
                          style: OutlinedButton.styleFrom(
                            foregroundColor: Colors.red,
                            side: const BorderSide(color: Colors.red),
                            padding: const EdgeInsets.symmetric(vertical: 14),
                            shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                          ),
                          child: isDeleting 
                            ? const SizedBox(width: 20, height: 20, child: CircularProgressIndicator(color: Colors.red, strokeWidth: 2))
                            : const Text('Hapus', style: TextStyle(fontWeight: FontWeight.bold)),
                        ),
                      ),
                      const SizedBox(width: 12),
                      Expanded(
                        child: ElevatedButton(
                          onPressed: isDeleting || isSaving ? null : () async {
                            final newName = nameController.text.trim();
                            if (newName.isEmpty || newName == device.label) {
                              Navigator.pop(context);
                              return;
                            }
                            setModalState(() => isSaving = true);
                            try {
                              await DeviceApiService().updateDevice(device.id, {'label': newName});
                              if (mounted) {
                                Navigator.pop(context);
                                _loadSavedDevices();
                              }
                            } catch (e) {
                              if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(e.toString())));
                            }
                            setModalState(() => isSaving = false);
                          },
                          style: ElevatedButton.styleFrom(
                            backgroundColor: const Color(0xFF003092),
                            foregroundColor: Colors.white,
                            padding: const EdgeInsets.symmetric(vertical: 14),
                            shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                          ),
                          child: isSaving 
                            ? const SizedBox(width: 20, height: 20, child: CircularProgressIndicator(color: Colors.white, strokeWidth: 2))
                            : const Text('Simpan', style: TextStyle(fontWeight: FontWeight.bold)),
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 24),
                ],
              ),
            );
          },
        );
      },
    );
  }
