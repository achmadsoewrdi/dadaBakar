import 'package:flutter/material.dart';
import 'package:flutter_bluetooth_serial/flutter_bluetooth_serial.dart';
import '../../../../core/services/device_connection_service.dart';
import '../../data/data_sources/device_api_service.dart';
import '../../data/models/device_profile_model.dart';
import '../../../auth/data/data_sources/auth_storage_service.dart';

class DeviceConnectionScreen extends StatefulWidget {
  final bool showBackButton;

  const DeviceConnectionScreen({super.key, this.showBackButton = false});

  @override
  State<DeviceConnectionScreen> createState() => _DeviceConnectionScreenState();
}

class _DeviceConnectionScreenState extends State<DeviceConnectionScreen> {
  final TextEditingController _ipController = TextEditingController();
  final TextEditingController _portController = TextEditingController();
  final TextEditingController _searchController = TextEditingController();
  
  List<DeviceProfileModel> _savedDevices = [];
  bool _isLoadingDevices = true;
  String? _connectingDeviceId;

  @override
  void initState() {
    super.initState();
    DeviceConnectionService.instance.loadPairedDevices(silent: true);
    _loadSavedDevices();
  }

  Future<void> _loadSavedDevices() async {
    setState(() => _isLoadingDevices = true);
    try {
      final devices = await DeviceApiService().getDevices();
      setState(() {
        _savedDevices = devices;
        _isLoadingDevices = false;
      });
    } catch (e) {
      if (mounted) {
        setState(() => _isLoadingDevices = false);
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Gagal memuat perangkat tersimpan: $e')),
        );
      }
    }
  }

  Future<void> _saveDevice(String label, String protocol, {String? macAddress, String? host, int? port}) async {
    try {
      final userId = AuthStorageService().currentUser?.id ?? '';
      final newDevice = DeviceProfileModel(
        id: '', // Will be generated by backend
        ownerId: userId,
        label: label,
        protocol: protocol,
        useTls: false,
        macAddress: macAddress,
        host: host,
        port: port,
        createdAt: DateTime.now(),
      );
      final profile = await DeviceApiService().createDevice(newDevice);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Berhasil menyimpan: ${profile.label}'),
            backgroundColor: Colors.green,
          ),
        );
      }
      _loadSavedDevices();
    } catch (e) {
      debugPrint("Gagal menyimpan device ke database: $e");
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Gagal menyimpan: $e'),
            backgroundColor: Colors.red,
          ),
        );
      }
    }
  }

  @override
  void dispose() {
    _ipController.dispose();
    _portController.dispose();
    _searchController.dispose();
    super.dispose();
  }

  void _showDeviceSelectionModal() {
    DeviceConnectionService.instance.loadPairedDevices();
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.white,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(24)),
      ),
      builder: (context) {
        return ListenableBuilder(
          listenable: DeviceConnectionService.instance,
          builder: (context, _) {
            final service = DeviceConnectionService.instance;
            return SafeArea(
              child: Padding(
                padding: const EdgeInsets.all(24.0),
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Text(
                      'Pilih Perangkat Bluetooth',
                      style: TextStyle(
                        fontSize: 18,
                        fontWeight: FontWeight.w800,
                        color: Color(0xFF0A122C),
